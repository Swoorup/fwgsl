fn rust_variant_ident(name: &str) -> String {
    let mut out = String::new();
    let mut capitalize = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            if capitalize {
                out.extend(ch.to_uppercase());
                capitalize = false;
            } else {
                out.push(ch);
            }
        } else {
            capitalize = true;
        }
    }
    if out.is_empty() {
        "Generated".into()
    } else {
        out
    }
}

fn rust_type_ident(name: &str) -> String {
    let ident = sanitize_identifier(name);
    if ident.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        format!("T{}", ident)
    } else {
        rust_variant_ident(&ident)
    }
}

fn rust_module_ident(name: &str) -> String {
    use heck::ToSnakeCase;
    rust_keyword_safe(&sanitize_identifier(name).to_snake_case())
}

fn rust_field_ident(name: &str) -> String {
    rust_keyword_safe(&sanitize_identifier(name).to_ascii_lowercase())
}

fn rust_keyword_safe(ident: &str) -> String {
    match ident {
        "fn" | "mod" | "type" | "struct" | "enum" | "crate" | "self" | "super" | "move" | "use"
        | "pub" | "impl" | "trait" | "const" | "let" | "where" | "match" | "loop" | "for"
        | "while" | "if" | "else" | "return" | "static" | "unsafe" => {
            format!("r#{}", ident)
        }
        _ => ident.to_string(),
    }
}

fn sanitize_identifier(name: &str) -> String {
    let mut ident = String::new();
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            ident.push(ch);
        } else {
            ident.push('_');
        }
    }
    if ident.is_empty() {
        "_".into()
    } else {
        ident
    }
}

fn sanitize_wgsl_identifier(name: &str) -> String {
    let prime_count = name.chars().rev().take_while(|&ch| ch == '\'').count();
    let base = &name[..name.len() - prime_count];
    let mut out = String::new();
    for ch in base.chars() {
        match ch {
            'a'..='z' | 'A'..='Z' | '0'..='9' | '_' => out.push(ch),
            _ => out.push('_'),
        }
    }
    if out.is_empty() {
        out.push('_');
    } else if out.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        out.insert(0, '_');
    }
    if matches!(
        out.as_str(),
        "alias"
            | "bitcast"
            | "bool"
            | "break"
            | "case"
            | "compute"
            | "const"
            | "continue"
            | "default"
            | "discard"
            | "else"
            | "enable"
            | "f32"
            | "false"
            | "fn"
            | "for"
            | "fragment"
            | "i32"
            | "if"
            | "let"
            | "loop"
            | "override"
            | "private"
            | "read"
            | "read_write"
            | "return"
            | "storage"
            | "struct"
            | "switch"
            | "true"
            | "u32"
            | "uniform"
            | "var"
            | "vertex"
            | "while"
            | "workgroup"
            | "write"
    ) {
        out.insert_str(0, "fw_");
    }
    if prime_count > 0 {
        out.push('_');
        out.push_str(&prime_count.to_string());
    }
    out
}

fn indent_line(output: &mut String, indent: usize, line: &str) {
    for _ in 0..indent {
        output.push_str("    ");
    }
    output.push_str(line);
    output.push('\n');
}

