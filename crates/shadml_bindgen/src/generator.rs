/// A structured error produced by the bindgen generator.
#[derive(Debug, Error, Clone)]
pub enum BindgenError {
    #[error("unsupported type: {0}")]
    UnsupportedType(String),
    #[error("missing attribute: {0}")]
    MissingAttribute(String),
    #[error("invalid manifest: {0}")]
    InvalidManifest(String),
}

#[derive(Default)]
struct ModuleNode {
    children: BTreeMap<String, ModuleNode>,
    entry_indices: Vec<usize>,
    type_names: BTreeSet<String>,
    /// Bind groups emitted at this module level, keyed by group number.
    /// Each bind group contains only bindings defined in this origin module.
    bind_groups: BTreeMap<u32, BindGroupInfo>,
}

#[derive(Clone)]
struct RegistryEntry {
    key: String,
    variant: String,
}

/// Emit a single `#[doc = "..."]` attribute for a doc-comment line.
fn emit_doc_line(output: &mut String, indent: usize, line: &str) {
    let escaped = line.replace('\\', "\\\\").replace('"', "\\\"");
    indent_line(output, indent, &format!(r#"#[doc = "{escaped}"]"#));
}

/// Emit `#[doc = "..."]` attributes for each line of an optional doc comment.
fn emit_doc_comment(output: &mut String, indent: usize, doc: Option<&str>) {
    if let Some(text) = doc {
        for line in text.lines() {
            emit_doc_line(output, indent, line);
        }
    }
}

/// Emit `#[doc = "..."]` attributes for each line of a multi-line comment vector.
fn emit_doc_comments(output: &mut String, indent: usize, comments: &[String]) {
    for comment in comments {
        for line in comment.lines() {
            emit_doc_line(output, indent, line);
        }
    }
}

/// Emit a plain `// ...` comment line (not a doc attribute).
/// Use this inside expressions where `#[doc]` would be unused.
fn emit_plain_comment(output: &mut String, indent: usize, line: &str) {
    indent_line(output, indent, &format!("// {}", line));
}

pub fn generate_rust_source(
    manifest: &ShaderBundleManifest,
    reflections: &ReflectedManifest,
    source_mode: SourceMode,
    type_map: TypeMapPreset,
) -> Result<String, BindgenError> {
    if manifest.profiles.is_empty() {
        return Err(BindgenError::InvalidManifest(
            "manifest did not contain any compiled profiles".into(),
        ));
    }

    let registry_entries = collect_registry_entries(manifest)?;
    let mut output = String::new();
    let mut layout_assertions: Vec<String> = Vec::new();

    writeln!(output, "// @generated by shadml_bindgen.\n").unwrap();
    render_shared_runtime(&mut output, manifest, source_mode);

    writeln!(output, "pub mod profiles {{").unwrap();
    for profile in &manifest.profiles {
        let reflection = reflections.get(&profile.profile_key).ok_or_else(|| {
            BindgenError::InvalidManifest(format!(
                "missing reflection for profile '{}'",
                profile.profile_key
            ))
        })?;
        render_profile_module(
            &mut output,
            &mut layout_assertions,
            &profile.profile_key,
            profile,
            reflection,
            source_mode,
            type_map,
            1,
        )?;
    }
    writeln!(output, "}}\n").unwrap();

    if !layout_assertions.is_empty() {
        writeln!(output, "pub mod layout_asserts {{").unwrap();
        for assertion in &layout_assertions {
            writeln!(output, "    {}", assertion).unwrap();
        }
        writeln!(output, "}}\n").unwrap();
    }

    render_registry(&mut output, manifest, reflections, &registry_entries)?;

    Ok(output)
}

fn render_shared_runtime(
    output: &mut String,
    manifest: &ShaderBundleManifest,
    source_mode: SourceMode,
) {
    let profile_variants = manifest
        .profiles
        .iter()
        .map(|profile| rust_variant_ident(&profile.profile_key))
        .collect::<Vec<_>>();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(
        output,
        "pub enum ShaderStage {{ Compute, Vertex, Fragment }}"
    )
    .unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(
        output,
        "pub enum ShaderProfile {{ {} }}",
        profile_variants.join(", ")
    )
    .unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(
        output,
        "pub enum SourceMode {{ EmbeddedDebug, EmbeddedMinified, RuntimeBlob, ServerFetch }}"
    )
    .unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(
        output,
        "pub enum ProfileCompatibility {{ AbiStable, AbiChanged }}"
    )
    .unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(
        output,
        "pub enum BindingAddressSpace {{ Uniform, StorageRead, StorageReadWrite, Immediate, Opaque }}"
    )
    .unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub struct BindingReflection {{").unwrap();
    writeln!(output, "    pub name: &'static str,").unwrap();
    writeln!(output, "    pub binding: u32,").unwrap();
    writeln!(output, "    pub address_space: BindingAddressSpace,").unwrap();
    writeln!(output, "    pub ty_name: &'static str,").unwrap();
    writeln!(output, "    pub min_binding_size: Option<u64>,").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub struct BindGroupReflection {{").unwrap();
    writeln!(output, "    pub group: u32,").unwrap();
    writeln!(output, "    pub bindings: &'static [BindingReflection],").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub struct EntryReflection {{").unwrap();
    writeln!(output, "    pub module_path: &'static str,").unwrap();
    writeln!(output, "    pub source_files: &'static [&'static str],").unwrap();
    writeln!(output, "    pub stage: ShaderStage,").unwrap();
    writeln!(output, "    pub entry_point: &'static str,").unwrap();
    writeln!(output, "    pub shader_name: &'static str,").unwrap();
    writeln!(
        output,
        "    pub bind_groups: &'static [BindGroupReflection],"
    )
    .unwrap();
    writeln!(output, "    pub workgroup_size: Option<[u32; 3]>,").unwrap();
    writeln!(output, "    pub push_constant_size: Option<u32>,").unwrap();
    writeln!(output, "    pub interface_hash: &'static str,").unwrap();
    writeln!(output, "    pub abi_hash: &'static str,").unwrap();
    writeln!(output, "    pub render_block: Option<&'static str>,").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub struct ShaderProfileInfo {{").unwrap();
    writeln!(output, "    pub key: &'static str,").unwrap();
    writeln!(output, "    pub feature_set: &'static [&'static str],").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub struct GeneratedShaderPackageInfo {{").unwrap();
    writeln!(output, "    pub source_mode: SourceMode,").unwrap();
    writeln!(output, "    pub profiles: &'static [ShaderProfileInfo],").unwrap();
    writeln!(output, "}}").unwrap();
    writeln!(output).unwrap();

    for profile in &manifest.profiles {
        writeln!(
            output,
            "const PROFILE_{}_FEATURES: &[&str] = &{};",
            rust_variant_ident(&profile.profile_key).to_uppercase(),
            string_slice_literal(&profile.enabled_features)
        )
        .unwrap();
    }
    writeln!(output).unwrap();

    writeln!(
        output,
        "pub const PACKAGE_INFO: GeneratedShaderPackageInfo = GeneratedShaderPackageInfo {{"
    )
    .unwrap();
    writeln!(
        output,
        "    source_mode: SourceMode::{},",
        source_mode_variant(source_mode)
    )
    .unwrap();
    writeln!(output, "    profiles: &[").unwrap();
    for profile in &manifest.profiles {
        let variant = rust_variant_ident(&profile.profile_key).to_uppercase();
        writeln!(
            output,
            "        ShaderProfileInfo {{ key: {:?}, feature_set: PROFILE_{}_FEATURES }},",
            profile.profile_key, variant
        )
        .unwrap();
    }
    writeln!(output, "    ],").unwrap();
    writeln!(output, "}};\n").unwrap();

    writeln!(output, "impl ShaderProfile {{").unwrap();
    writeln!(output, "    pub fn key(self) -> &'static str {{").unwrap();
    writeln!(output, "        match self {{").unwrap();
    for profile in &manifest.profiles {
        writeln!(
            output,
            "            ShaderProfile::{} => {:?},",
            rust_variant_ident(&profile.profile_key),
            profile.profile_key
        )
        .unwrap();
    }
    writeln!(output, "        }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(
        output,
        "    pub fn feature_set(self) -> &'static [&'static str] {{"
    )
    .unwrap();
    writeln!(output, "        match self {{").unwrap();
    for profile in &manifest.profiles {
        writeln!(
            output,
            "            ShaderProfile::{} => PROFILE_{}_FEATURES,",
            rust_variant_ident(&profile.profile_key),
            rust_variant_ident(&profile.profile_key).to_uppercase()
        )
        .unwrap();
    }
    writeln!(output, "        }}").unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(output, "}}\n").unwrap();
}

#[allow(clippy::too_many_arguments)]
fn render_profile_module(
    output: &mut String,
    layout_assertions: &mut Vec<String>,
    profile_key: &str,
    profile: &CompiledProfile,
    reflection: &ReflectedProfile,
    source_mode: SourceMode,
    type_map: TypeMapPreset,
    indent: usize,
) -> Result<(), BindgenError> {
    let module_name = rust_module_ident(&profile.profile_key);
    let mut module_tree = ModuleNode::default();

    for (index, entry) in profile.entries.iter().enumerate() {
        insert_entry(&mut module_tree, entry, index);
    }
    insert_exported_types(&mut module_tree, profile);
    insert_bind_groups(&mut module_tree, profile);

    indent_line(output, indent, &format!("pub mod {} {{", module_name));
    indent_line(
        output,
        indent + 1,
        &format!("pub const PROFILE_KEY: &str = {:?};", profile.profile_key),
    );
    indent_line(
        output,
        indent + 1,
        &format!(
            "pub const FEATURE_SET: &[&str] = &{};",
            string_slice_literal(&profile.enabled_features)
        ),
    );
    output.push('\n');

    for (segment, child) in &module_tree.children {
        render_module(
            output,
            layout_assertions,
            profile_key,
            child,
            std::slice::from_ref(segment),
            profile,
            reflection,
            source_mode,
            type_map,
            indent + 1,
        )?;
    }

    indent_line(output, indent, "}");
    output.push('\n');
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn render_module(
    output: &mut String,
    layout_assertions: &mut Vec<String>,
    profile_key: &str,
    node: &ModuleNode,
    module_path: &[String],
    profile: &CompiledProfile,
    reflection: &ReflectedProfile,
    source_mode: SourceMode,
    type_map: TypeMapPreset,
    indent: usize,
) -> Result<(), BindgenError> {
    let module_name = rust_module_ident(module_path.last().ok_or_else(|| {
        BindgenError::InvalidManifest("empty module path in render_module".into())
    })?);
    indent_line(output, indent, &format!("pub mod {} {{", module_name));
    indent_line(
        output,
        indent + 1,
        &format!("pub const MODULE_PATH: &str = {:?};", module_path.join(".")),
    );
    output.push('\n');

    // Collect unique entry paths from entries in this module for reflection lookup.
    let mut candidate_paths: Vec<Vec<String>> = Vec::new();
    for &entry_index in &node.entry_indices {
        let path = profile.entries[entry_index].rust_mod_path.clone();
        if !candidate_paths.contains(&path) {
            candidate_paths.push(path);
        }
    }

    for type_name in &node.type_names {
        let exported = profile
            .exported_types
            .iter()
            .find(|e| e.name == *type_name && e.rust_mod_path.as_slice() == module_path)
            .ok_or_else(|| {
                BindgenError::InvalidManifest(format!("missing exported type '{}'", type_name))
            })?;
        render_gpu_struct(
            output,
            layout_assertions,
            profile_key,
            exported,
            module_path,
            &candidate_paths,
            reflection,
            type_map,
            indent + 1,
        )?;
        render_vertex_struct(
            output,
            layout_assertions,
            profile_key,
            exported,
            module_path,
            &candidate_paths,
            reflection,
            type_map,
            indent + 1,
        )?;
    }

    // Build merged binding sizes for bind groups emitted at this module level.
    let mut binding_sizes_map: BTreeMap<u32, BTreeMap<String, Option<u64>>> = BTreeMap::new();
    for entry in &profile.entries {
        for bind_group in &entry.bind_groups {
            let origin = bind_group_origin(entry, bind_group);
            if origin.as_slice() == module_path {
                let sizes = binding_sizes_map.entry(bind_group.group).or_default();
                if let Some(reflected) = reflection.entries.get(&entry.shader_name) {
                    for (name, size) in &reflected.binding_sizes {
                        sizes.insert(name.clone(), *size);
                    }
                }
            }
        }
    }

    for (group, bind_group) in &node.bind_groups {
        let binding_sizes = binding_sizes_map.get(group).cloned().unwrap_or_default();
        render_bind_group_module(
            output,
            bind_group,
            &binding_sizes,
            &module_path.join("."),
            indent + 1,
        )?;
    }

    for &entry_index in &node.entry_indices {
        render_entry_module(
            output,
            &profile.entries[entry_index],
            reflection,
            indent + 1,
            source_mode,
        )?;
    }

    // Generate per-render-block pipeline layouts for this module.
    render_module_render_layouts(output, node, profile, reflection, module_path, indent + 1)?;

    for (segment, child) in &node.children {
        let mut child_path = module_path.to_vec();
        child_path.push(segment.clone());
        render_module(
            output,
            layout_assertions,
            profile_key,
            child,
            &child_path,
            profile,
            reflection,
            source_mode,
            type_map,
            indent + 1,
        )?;
    }

    indent_line(output, indent, "}");
    output.push('\n');
    Ok(())
}

/// Generate per-render-block pipeline layout functions for this module.
///
/// For each render block in the module, generates a pipeline layout function
/// with `VERTEX | FRAGMENT` visibility for all bindings.
fn render_module_render_layouts(
    output: &mut String,
    node: &ModuleNode,
    profile: &CompiledProfile,
    reflection: &ReflectedProfile,
    module_path: &[String],
    indent: usize,
) -> Result<(), BindgenError> {
    let module_name_str = module_path.last().ok_or_else(|| {
        BindgenError::InvalidManifest("empty module path in render_module_render_layouts".into())
    })?;

    // Group entries by render_block name
    let mut render_block_entries: BTreeMap<String, Vec<usize>> = BTreeMap::new();

    for &idx in &node.entry_indices {
        let entry = &profile.entries[idx];
        if let Some(ref rb_name) = entry.render_block {
            render_block_entries
                .entry(rb_name.clone())
                .or_default()
                .push(idx);
        }
    }

    // Generate per-render-block pipeline layout functions
    for (rb_name, rb_entry_indices) in &render_block_entries {
        render_render_block_pipeline_layout(
            output,
            rb_name,
            rb_entry_indices,
            profile,
            reflection,
            module_name_str,
            indent,
        )?;
    }

    Ok(())
}

/// Generate a per-render-block pipeline layout with VERTEX | FRAGMENT visibility
/// for all bindings.
fn render_render_block_pipeline_layout(
    output: &mut String,
    render_block_name: &str,
    entry_indices: &[usize],
    profile: &CompiledProfile,
    reflection: &ReflectedProfile,
    module_name_str: &str,
    indent: usize,
) -> Result<(), BindgenError> {
    // Collect all unique group numbers across entries in this render block.
    let mut group_set: BTreeSet<u32> = BTreeSet::new();
    for &entry_idx in entry_indices {
        let entry = &profile.entries[entry_idx];
        for bg in &entry.bind_groups {
            group_set.insert(bg.group);
        }
    }

    // Track push constant sizes
    let mut max_immediate_size: u32 = 0;
    for &entry_idx in entry_indices {
        let entry = &profile.entries[entry_idx];
        let entry_reflected = reflection.entries.get(&entry.shader_name).ok_or_else(|| {
            BindgenError::InvalidManifest(format!(
                "missing reflection for entry '{}'",
                entry.shader_name
            ))
        })?;
        if let Some(pc_size) = entry_reflected.push_constant_size {
            max_immediate_size = max_immediate_size.max(pc_size);
        } else if let Some(ref pc) = entry.push_constants {
            max_immediate_size = max_immediate_size.max(pc.size);
        }
    }

    let rb_ident = rust_module_ident(render_block_name);
    let label = format!("{}-{}-render", module_name_str, rb_ident);

    // Generate the render block pipeline layout function, referencing
    // deduplicated module-level bind group layouts.
    indent_line(
        output,
        indent,
        &format!("pub fn create_{}_render_pipeline_layout(device: &wgpu::Device) -> wgpu::PipelineLayout {{", rb_ident),
    );

    for group_idx in &group_set {
        // Find the origin module for this group
        let mut group_origin = None;
        for &entry_idx in entry_indices {
            let entry = &profile.entries[entry_idx];
            if let Some(bg) = entry.bind_groups.iter().find(|bg| bg.group == *group_idx) {
                group_origin = Some(bind_group_origin(entry, bg));
                break;
            }
        }
        let origin = group_origin.unwrap_or_else(|| vec![module_name_str.to_string()]);
        let rel = relative_module_path(&[module_name_str.to_string()], &origin);
        let path = if rel == "self" {
            format!("group{}", group_idx)
        } else {
            format!("{}::group{}", rel, group_idx)
        };
        indent_line(
            output,
            indent + 1,
            &format!(
                "let group{}_layout = {}::create_bind_group_layout(device);",
                group_idx, path
            ),
        );
    }

    let bind_group_layouts: Vec<String> = group_set
        .iter()
        .map(|g| format!("Some(&group{}_layout)", g))
        .collect();
    indent_line(
        output,
        indent + 1,
        &format!(
            "let bind_group_layouts = [{}];",
            bind_group_layouts.join(", ")
        ),
    );
    indent_line(
        output,
        indent + 1,
        "device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {",
    );
    indent_line(output, indent + 2, &format!("label: Some(\"{}\"),", label));
    indent_line(
        output,
        indent + 2,
        "bind_group_layouts: &bind_group_layouts,",
    );
    indent_line(
        output,
        indent + 2,
        &format!("immediate_size: {},", max_immediate_size),
    );
    indent_line(output, indent + 1, "})");

    indent_line(output, indent, "}");
    output.push('\n');

    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn render_gpu_struct(
    output: &mut String,
    layout_assertions: &mut Vec<String>,
    profile_key: &str,
    exported: &ExportedType,
    module_path: &[String],
    candidate_paths: &[Vec<String>],
    reflection: &ReflectedProfile,
    type_map: TypeMapPreset,
    indent: usize,
) -> Result<(), BindgenError> {
    let sanitized_name = sanitize_wgsl_identifier(&exported.name);
    let layout = find_reflected_layout(reflection, module_path, &sanitized_name, candidate_paths)
        .ok_or_else(|| {
        BindgenError::InvalidManifest(format!(
            "missing reflected layout for type '{}'",
            exported.name
        ))
    })?;
    let struct_name = format!("{}Wire", rust_type_ident(&exported.name));
    let rust_module_path = module_path
        .iter()
        .map(|s| rust_module_ident(s))
        .collect::<Vec<_>>()
        .join("::");
    let fq_struct_name = format!(
        "super::profiles::{}::{}::{}",
        rust_module_ident(profile_key),
        rust_module_path,
        struct_name
    );

    emit_doc_comments(output, indent, &exported.comments);
    indent_line(
        output,
        indent,
        &format!("#[repr(C, align({}))]", layout.alignment),
    );
    indent_line(output, indent, "#[derive(Clone, Copy, Debug)]");
    indent_line(output, indent, &format!("pub struct {} {{", struct_name));

    let mut current_offset = 0u32;
    let mut padding_index = 0usize;
    let mut padding_fields: Vec<(usize, u32)> = Vec::new();
    for field in &exported.fields {
        let field_layout = layout
            .fields
            .iter()
            .find(|candidate| candidate.name == sanitize_wgsl_identifier(&field.name))
            .ok_or_else(|| {
                BindgenError::InvalidManifest(format!(
                    "missing reflected field '{}' in type '{}'",
                    field.name, exported.name
                ))
            })?;

        if field_layout.offset > current_offset {
            let padding = field_layout.offset - current_offset;
            indent_line(
                output,
                indent + 1,
                &format!(
                    "pub _pad{}: std::mem::MaybeUninit<[u8; {}]>,",
                    padding_index, padding
                ),
            );
            padding_fields.push((padding_index, padding));
            current_offset += padding;
            padding_index += 1;
        }

        emit_doc_comment(output, indent + 1, field.doc.as_deref());
        let wgsl_ty = manifest_type_name(&field.ty);
        indent_line(
            output,
            indent + 1,
            &format!(
                r#"#[doc = "offset: {}, size: {}, type: `{}`"]"#,
                field_layout.offset, field_layout.size, wgsl_ty
            ),
        );
        indent_line(
            output,
            indent + 1,
            &format!(
                "pub {}: {},",
                rust_field_ident(&field.name),
                rust_wire_type(&field.ty)?
            ),
        );
        current_offset += rust_wire_size(&field.ty, module_path, reflection)?;
    }

    if layout.size > current_offset {
        indent_line(
            output,
            indent + 1,
            &format!(
                "pub _pad{}: std::mem::MaybeUninit<[u8; {}]>,",
                padding_index,
                layout.size - current_offset
            ),
        );
        padding_fields.push((padding_index, layout.size - current_offset));
    }

    indent_line(output, indent, "}");
    indent_line(
        output,
        indent,
        &format!("unsafe impl bytemuck::Zeroable for {} {{}}", struct_name),
    );
    indent_line(
        output,
        indent,
        &format!("unsafe impl bytemuck::Pod for {} {{}}", struct_name),
    );
    layout_assertions.push(format!(
        "const _: [(); {}usize] = [(); ::core::mem::size_of::<{}>()];",
        layout.size, fq_struct_name
    ));
    layout_assertions.push(format!(
        "const _: [(); {}usize] = [(); ::core::mem::align_of::<{}>()];",
        layout.alignment, fq_struct_name
    ));
    for field in &exported.fields {
        let field_layout = layout
            .fields
            .iter()
            .find(|candidate| candidate.name == sanitize_wgsl_identifier(&field.name))
            .ok_or_else(|| {
                BindgenError::InvalidManifest(format!(
                    "field layout for '{}' disappeared after initial lookup in type '{}'",
                    field.name, exported.name
                ))
            })?;
        layout_assertions.push(format!(
            "const _: [(); {}usize] = [(); ::core::mem::offset_of!({}, {})];",
            field_layout.offset,
            fq_struct_name,
            rust_field_ident(&field.name)
        ));
    }
    output.push('\n');

    // Emit clean surface type and From impl
    let clean_name = rust_type_ident(&exported.name);
    if let Some(ref variants) = exported.adt_variants {
        // ADT: emit Rust enum
        emit_doc_comments(output, indent, &exported.comments);
        indent_line(output, indent, "#[derive(Clone, Copy, Debug, PartialEq)]");
        indent_line(output, indent, &format!("pub enum {} {{", clean_name));
        let variant_count = variants.len();
        for (i, variant) in variants.iter().enumerate() {
            let trailing = if i + 1 < variant_count { "," } else { "" };
            emit_doc_comment(output, indent + 1, variant.doc.as_deref());
            if variant.fields.is_empty() {
                indent_line(
                    output,
                    indent + 1,
                    &format!(
                        "{} = {}{}",
                        rust_variant_ident(&variant.name),
                        variant.tag,
                        trailing
                    ),
                );
            } else {
                let field_decls: Vec<String> = variant
                    .fields
                    .iter()
                    .map(|f| {
                        format!(
                            "{}: {}",
                            rust_field_ident(&f.name),
                            clean_rust_type(&f.ty, type_map).unwrap_or_else(|_| "()".into())
                        )
                    })
                    .collect();
                indent_line(
                    output,
                    indent + 1,
                    &format!(
                        "{} {{ {} }}{}",
                        rust_variant_ident(&variant.name),
                        field_decls.join(", "),
                        trailing
                    ),
                );
            }
        }
        indent_line(output, indent, "}");
        output.push('\n');

        // From<CleanEnum> for WireStruct
        indent_line(
            output,
            indent,
            &format!("impl From<{}> for {} {{", clean_name, struct_name),
        );
        indent_line(
            output,
            indent + 1,
            &format!("fn from(value: {}) -> Self {{", clean_name),
        );
        indent_line(output, indent + 2, "match value {");
        let arm_count = variants.len();
        for (i, variant) in variants.iter().enumerate() {
            let trailing = if i + 1 < arm_count { "," } else { "" };
            let pat_fields: Vec<String> = variant
                .fields
                .iter()
                .map(|f| rust_field_ident(&f.name))
                .collect();
            let mut body_lines = Vec::new();
            body_lines.push(format!("tag: {},", variant.tag));
            for (idx, _) in padding_fields.iter().enumerate() {
                body_lines.push(format!(
                    "_pad{}: unsafe {{ std::mem::MaybeUninit::zeroed().assume_init() }},",
                    idx
                ));
            }
            for field in &variant.fields {
                let field_name = rust_field_ident(&field.name);
                let wire_expr = clean_to_wire_expr(&field_name, &field.ty, type_map);
                // In match arms we destructure, so `value.` prefix should be stripped
                let wire_expr = wire_expr.replace(&format!("value.{}", field_name), &field_name);
                body_lines.push(format!("{}: {},", field_name, wire_expr));
            }
            if variant.fields.is_empty() {
                indent_line(
                    output,
                    indent + 3,
                    &format!(
                        "{}::{} => Self {{ {} }}{}",
                        clean_name,
                        rust_variant_ident(&variant.name),
                        body_lines.join(" "),
                        trailing
                    ),
                );
            } else {
                indent_line(
                    output,
                    indent + 3,
                    &format!(
                        "{}::{} {{ {} }} => Self {{ {} }}{}",
                        clean_name,
                        rust_variant_ident(&variant.name),
                        pat_fields.join(", "),
                        body_lines.join(" "),
                        trailing
                    ),
                );
            }
        }
        indent_line(output, indent + 2, "}");
        indent_line(output, indent + 1, "}");
        indent_line(output, indent, "}");
        output.push('\n');
    } else if let Some(ref bf_fields) = exported.bitfield_fields {
        // Bitfield: emit builder struct
        emit_doc_comments(output, indent, &exported.comments);
        indent_line(
            output,
            indent,
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        );
        indent_line(output, indent, &format!("pub struct {} {{", clean_name));
        indent_line(output, indent + 1, "pub raw: u32,");
        indent_line(output, indent, "}");
        output.push('\n');

        indent_line(output, indent, &format!("impl {} {{", clean_name));
        indent_line(output, indent + 1, "pub fn new() -> Self {");
        indent_line(output, indent + 2, "Self { raw: 0 }");
        indent_line(output, indent + 1, "}");
        for bf in bf_fields {
            emit_doc_comment(output, indent + 1, bf.doc.as_deref());
            let mask = (1u32 << bf.width).wrapping_sub(1);
            let param_ty = if bf.width == 1 {
                "bool"
            } else if bf.width <= 8 {
                "u8"
            } else if bf.width <= 16 {
                "u16"
            } else {
                "u32"
            };
            indent_line(
                output,
                indent + 1,
                &format!(
                    "pub fn {}(self, value: {}) -> Self {{",
                    rust_field_ident(&bf.name),
                    param_ty
                ),
            );
            let value_expr = "(value as u32)".to_string();
            let clear = if bf.offset == 0 {
                format!("self.raw & !{}u32", mask)
            } else {
                format!("self.raw & !({}u32 << {})", mask, bf.offset)
            };
            let set = if bf.offset == 0 {
                format!("{} & {}u32", value_expr, mask)
            } else {
                format!("({} & {}u32) << {}", value_expr, mask, bf.offset)
            };
            indent_line(
                output,
                indent + 2,
                &format!("Self {{ raw: ({}) | ({}) }}", clear, set),
            );
            indent_line(output, indent + 1, "}");
        }
        indent_line(output, indent, "}");
        output.push('\n');

        indent_line(
            output,
            indent,
            &format!("impl Default for {} {{", clean_name),
        );
        indent_line(output, indent + 1, "fn default() -> Self { Self::new() }");
        indent_line(output, indent, "}");
        output.push('\n');

        indent_line(
            output,
            indent,
            &format!("impl From<{}> for {} {{", clean_name, struct_name),
        );
        indent_line(
            output,
            indent + 1,
            &format!("fn from(value: {}) -> Self {{", clean_name),
        );
        indent_line(output, indent + 2, "Self { raw: value.raw }");
        indent_line(output, indent + 1, "}");
        indent_line(output, indent, "}");
        output.push('\n');
    } else {
        // Plain struct: emit clean struct
        emit_doc_comments(output, indent, &exported.comments);
        indent_line(output, indent, "#[derive(Clone, Copy, Debug, PartialEq)]");
        indent_line(output, indent, &format!("pub struct {} {{", clean_name));
        for field in &exported.fields {
            emit_doc_comment(output, indent + 1, field.doc.as_deref());
            let field_layout = layout
                .fields
                .iter()
                .find(|candidate| candidate.name == sanitize_wgsl_identifier(&field.name))
                .ok_or_else(|| {
                    BindgenError::InvalidManifest(format!(
                        "missing reflected field '{}' in type '{}'",
                        field.name, exported.name
                    ))
                })?;
            let wgsl_ty = manifest_type_name(&field.ty);
            indent_line(
                output,
                indent + 1,
                &format!(
                    r#"#[doc = "offset: {}, size: {}, type: `{}`"]"#,
                    field_layout.offset, field_layout.size, wgsl_ty
                ),
            );
            indent_line(
                output,
                indent + 1,
                &format!(
                    "pub {}: {},",
                    rust_field_ident(&field.name),
                    clean_rust_type(&field.ty, type_map)?
                ),
            );
        }
        indent_line(output, indent, "}");
        output.push('\n');

        // From<Clean> for Wire
        indent_line(
            output,
            indent,
            &format!("impl From<{}> for {} {{", clean_name, struct_name),
        );
        indent_line(
            output,
            indent + 1,
            &format!("fn from(value: {}) -> Self {{", clean_name),
        );
        indent_line(output, indent + 2, "Self {");
        for (idx, _) in &padding_fields {
            indent_line(
                output,
                indent + 3,
                &format!(
                    "_pad{}: unsafe {{ std::mem::MaybeUninit::zeroed().assume_init() }},",
                    idx
                ),
            );
        }
        for field in &exported.fields {
            let field_name = rust_field_ident(&field.name);
            indent_line(
                output,
                indent + 3,
                &format!(
                    "{}: {},",
                    field_name,
                    clean_to_wire_expr(&field_name, &field.ty, type_map)
                ),
            );
        }
        indent_line(output, indent + 2, "}");
        indent_line(output, indent + 1, "}");
        indent_line(output, indent, "}");
        output.push('\n');
    }

    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn render_vertex_struct(
    output: &mut String,
    layout_assertions: &mut Vec<String>,
    profile_key: &str,
    exported: &ExportedType,
    module_path: &[String],
    candidate_paths: &[Vec<String>],
    reflection: &ReflectedProfile,
    _type_map: TypeMapPreset,
    indent: usize,
) -> Result<(), BindgenError> {
    let sanitized_name = sanitize_wgsl_identifier(&exported.name);
    let layout = find_reflected_layout(reflection, module_path, &sanitized_name, candidate_paths)
        .ok_or_else(|| {
        BindgenError::InvalidManifest(format!(
            "missing reflected layout for type '{}'",
            exported.name
        ))
    })?;

    // Collect fields that have @location attributes, preserving declaration order.
    let mut location_fields: Vec<(&ExportedField, u32, u32)> = Vec::new();
    for field in &exported.fields {
        if field_has_location(field) {
            let field_layout = layout
                .fields
                .iter()
                .find(|candidate| candidate.name == sanitize_wgsl_identifier(&field.name))
                .ok_or_else(|| {
                    BindgenError::InvalidManifest(format!(
                        "missing reflected field '{}' in type '{}'",
                        field.name, exported.name
                    ))
                })?;
            let shader_location = field_location_index(field)?;
            location_fields.push((field, field_layout.offset, shader_location));
        }
    }

    if location_fields.is_empty() {
        return Ok(());
    }

    let struct_name = format!("{}Vertex", rust_type_ident(&exported.name));
    let rust_module_path = module_path
        .iter()
        .map(|s| rust_module_ident(s))
        .collect::<Vec<_>>()
        .join("::");
    let fq_struct_name = format!(
        "super::profiles::{}::{}::{}",
        rust_module_ident(profile_key),
        rust_module_path,
        struct_name
    );

    emit_doc_comments(output, indent, &exported.comments);
    indent_line(output, indent, "#[repr(C)]");
    indent_line(output, indent, "#[derive(Clone, Copy, Debug, PartialEq)]");
    indent_line(output, indent, &format!("pub struct {} {{", struct_name));

    let mut current_offset = 0u32;
    let mut padding_index = 0usize;
    for (field, wgsl_offset, _shader_location) in &location_fields {
        if *wgsl_offset > current_offset {
            let padding = wgsl_offset - current_offset;
            indent_line(
                output,
                indent + 1,
                &format!("pub _pad{}: [u8; {}],", padding_index, padding),
            );
            current_offset += padding;
            padding_index += 1;
        }

        emit_doc_comment(output, indent + 1, field.doc.as_deref());
        let field_layout = layout
            .fields
            .iter()
            .find(|candidate| candidate.name == sanitize_wgsl_identifier(&field.name))
            .ok_or_else(|| {
                BindgenError::InvalidManifest(format!(
                    "missing reflected field '{}' in type '{}'",
                    field.name, exported.name
                ))
            })?;
        let wgsl_ty = manifest_type_name(&field.ty);
        indent_line(
            output,
            indent + 1,
            &format!(
                r#"#[doc = "offset: {}, size: {}, type: `{}`"]"#,
                field_layout.offset, field_layout.size, wgsl_ty
            ),
        );
        indent_line(
            output,
            indent + 1,
            &format!(
                "pub {}: {},",
                rust_field_ident(&field.name),
                rust_wire_type(&field.ty)?
            ),
        );
        current_offset += rust_wire_size(&field.ty, module_path, reflection)?;
    }

    indent_line(output, indent, "}");
    indent_line(
        output,
        indent,
        &format!("unsafe impl bytemuck::Zeroable for {} {{}}", struct_name),
    );
    indent_line(
        output,
        indent,
        &format!("unsafe impl bytemuck::Pod for {} {{}}", struct_name),
    );

    let vertex_size = current_offset;
    layout_assertions.push(format!(
        "const _: [(); {}usize] = [(); ::core::mem::size_of::<{}>()];",
        vertex_size, fq_struct_name
    ));
    for (field, field_offset, _shader_location) in &location_fields {
        layout_assertions.push(format!(
            "const _: [(); {}usize] = [(); ::core::mem::offset_of!({}, {})];",
            field_offset,
            fq_struct_name,
            rust_field_ident(&field.name)
        ));
    }
    output.push('\n');

    // Generate vertex_buffer_layout() helper.
    indent_line(output, indent, &format!("impl {} {{", struct_name));
    indent_line(
        output,
        indent + 1,
        "pub fn vertex_buffer_layout() -> wgpu::VertexBufferLayout<'static> {",
    );
    indent_line(
        output,
        indent + 2,
        &format!(
            "const ARRAY_STRIDE: u64 = ::core::mem::size_of::<{}>() as u64;",
            struct_name
        ),
    );
    indent_line(
        output,
        indent + 2,
        "const ATTRIBUTES: &[wgpu::VertexAttribute] = &[",
    );
    for (field, field_offset, shader_location) in &location_fields {
        let format = wgpu_vertex_format_from_type(&field.ty)?;
        indent_line(output, indent + 3, "wgpu::VertexAttribute {");
        indent_line(output, indent + 4, &format!("offset: {}u64,", field_offset));
        indent_line(
            output,
            indent + 4,
            &format!("format: wgpu::VertexFormat::{},", format),
        );
        indent_line(
            output,
            indent + 4,
            &format!("shader_location: {},", shader_location),
        );
        indent_line(output, indent + 3, "},");
    }
    indent_line(output, indent + 2, "];");
    indent_line(output, indent + 2, "wgpu::VertexBufferLayout {");
    indent_line(output, indent + 3, "array_stride: ARRAY_STRIDE,");
    indent_line(
        output,
        indent + 3,
        "step_mode: wgpu::VertexStepMode::Vertex,",
    );
    indent_line(output, indent + 3, "attributes: ATTRIBUTES,");
    indent_line(output, indent + 2, "}");
    indent_line(output, indent + 1, "}");
    indent_line(output, indent, "}");
    output.push('\n');

    Ok(())
}

/// Known shader field attribute names used by the bindgen.
mod attr {
    pub const LOCATION: &str = "location";
}

fn field_has_location(field: &ExportedField) -> bool {
    field
        .attributes
        .iter()
        .any(|attr| attr.name == attr::LOCATION)
}

fn field_location_index(field: &ExportedField) -> Result<u32, BindgenError> {
    for attr in &field.attributes {
        if attr.name == attr::LOCATION {
            if let Some(arg) = attr.args.first() {
                return arg.parse().map_err(|e| {
                    BindgenError::InvalidManifest(format!(
                        "invalid @location argument '{}' for field '{}': {}",
                        arg, field.name, e
                    ))
                });
            } else {
                return Err(BindgenError::MissingAttribute(format!(
                    "missing @location argument for field '{}'",
                    field.name
                )));
            }
        }
    }
    Err(BindgenError::InvalidManifest(format!(
        "field '{}' has no @location attribute",
        field.name
    )))
}

fn wgpu_vertex_format_from_type(ty: &ManifestType) -> Result<&'static str, BindgenError> {
    match ty {
        ManifestType::F32 => Ok("Float32"),
        ManifestType::U32 => Ok("Uint32"),
        ManifestType::I32 => Ok("Sint32"),
        ManifestType::Vec(2, inner) if matches!(inner.as_ref(), ManifestType::F32) => {
            Ok("Float32x2")
        }
        ManifestType::Vec(3, inner) if matches!(inner.as_ref(), ManifestType::F32) => {
            Ok("Float32x3")
        }
        ManifestType::Vec(4, inner) if matches!(inner.as_ref(), ManifestType::F32) => {
            Ok("Float32x4")
        }
        ManifestType::Vec(2, inner) if matches!(inner.as_ref(), ManifestType::U32) => {
            Ok("Uint32x2")
        }
        ManifestType::Vec(3, inner) if matches!(inner.as_ref(), ManifestType::U32) => {
            Ok("Uint32x3")
        }
        ManifestType::Vec(4, inner) if matches!(inner.as_ref(), ManifestType::U32) => {
            Ok("Uint32x4")
        }
        ManifestType::Vec(2, inner) if matches!(inner.as_ref(), ManifestType::I32) => {
            Ok("Sint32x2")
        }
        ManifestType::Vec(3, inner) if matches!(inner.as_ref(), ManifestType::I32) => {
            Ok("Sint32x3")
        }
        ManifestType::Vec(4, inner) if matches!(inner.as_ref(), ManifestType::I32) => {
            Ok("Sint32x4")
        }
        _ => Err(BindgenError::InvalidManifest(format!(
            "unsupported vertex buffer type: {:?}",
            ty
        ))),
    }
}

fn render_entry_module(
    output: &mut String,
    entry: &CompiledEntry,
    reflection: &ReflectedProfile,
    indent: usize,
    source_mode: SourceMode,
) -> Result<(), BindgenError> {
    let reflected_entry = reflection.entries.get(&entry.shader_name).ok_or_else(|| {
        BindgenError::InvalidManifest(format!(
            "missing reflected entry metadata for '{}'",
            entry.shader_name
        ))
    })?;
    let interface_hash = interface_hash(entry, reflected_entry);
    let abi_hash = abi_hash(entry, reflected_entry, reflection);
    let source_files = entry
        .source_files
        .iter()
        .map(|path| path.to_string_lossy().replace('\\', "/"))
        .collect::<Vec<_>>();

    emit_doc_comments(output, indent, &entry.comments);
    indent_line(
        output,
        indent,
        &format!("pub mod {} {{", entry_module_ident(entry)),
    );
    if entry.bind_groups.is_empty() {
        indent_line(
            output,
            indent + 1,
            "use crate::generated::{BindGroupReflection, EntryReflection, ShaderStage};",
        );
    } else {
        indent_line(
            output,
            indent + 1,
            "use crate::generated::{BindGroupReflection, BindingAddressSpace, BindingReflection, EntryReflection, ShaderStage};",
        );
    }
    indent_line(
        output,
        indent + 1,
        &format!("pub const SHADER_NAME: &str = {:?};", entry.shader_name),
    );
    indent_line(
        output,
        indent + 1,
        &format!("pub const ENTRY_POINT: &str = {:?};", entry.entry_point),
    );
    indent_line(
        output,
        indent + 1,
        &format!(
            "pub const STAGE: ShaderStage = ShaderStage::{};",
            shader_stage_variant(entry.stage)
        ),
    );
    indent_line(
        output,
        indent + 1,
        &format!("pub const INTERFACE_HASH: &str = {:?};", interface_hash),
    );
    indent_line(
        output,
        indent + 1,
        &format!("pub const ABI_HASH: &str = {:?};", abi_hash),
    );
    indent_line(
        output,
        indent + 1,
        &format!(
            "pub const SOURCE_FILES: &[&str] = &{};",
            string_slice_literal(&source_files)
        ),
    );
    indent_line(
        output,
        indent + 1,
        &format!(
            "pub const WGSL_SOURCE: &str = {};",
            raw_string_literal(&embedded_source(&entry.wgsl_source, source_mode))
        ),
    );
    output.push('\n');

    // Generate push constant type alias and helpers
    if let Some(pc) = &entry.push_constants {
        if let ManifestType::Struct(type_name) = &pc.ty {
            let wire_struct_name = format!("{}Wire", rust_type_ident(type_name));
            // Type alias: ImmediatesWire = the push constant struct already rendered at profile level
            indent_line(
                output,
                indent + 1,
                &format!("pub type ImmediatesWire = super::{};", wire_struct_name),
            );

            let pc_size = reflected_entry
                .push_constant_size
                .unwrap_or_else(|| entry.push_constants.as_ref().map(|pc| pc.size).unwrap_or(0));
            indent_line(
                output,
                indent + 1,
                &format!("pub const PUSH_CONSTANT_SIZE: u32 = {};", pc_size),
            );
            output.push('\n');

            // set_immediates for render passes
            indent_line(
                output,
                indent + 1,
                "pub fn set_immediates(pass: &mut wgpu::RenderPass, data: &ImmediatesWire) {",
            );
            indent_line(
                output,
                indent + 2,
                "pass.set_immediates(0, bytemuck::cast_slice(std::slice::from_ref(data)));",
            );
            indent_line(output, indent + 1, "}");
            output.push('\n');

            // set_immediates for compute passes
            indent_line(
                output,
                indent + 1,
                "pub fn set_immediates_compute(pass: &mut wgpu::ComputePass, data: &ImmediatesWire) {",
            );
            indent_line(
                output,
                indent + 2,
                "pass.set_immediates(0, bytemuck::cast_slice(std::slice::from_ref(data)));",
            );
            indent_line(output, indent + 1, "}");
            output.push('\n');
        }
    }

    render_entry_reflection(
        output,
        entry,
        reflected_entry,
        &source_files,
        &interface_hash,
        &abi_hash,
        indent + 1,
    );

    indent_line(
        output,
        indent + 1,
        "pub fn create_shader_module(device: &wgpu::Device) -> wgpu::ShaderModule {",
    );
    indent_line(
        output,
        indent + 2,
        "device.create_shader_module(wgpu::ShaderModuleDescriptor {",
    );
    indent_line(output, indent + 3, "label: Some(SHADER_NAME),");
    indent_line(
        output,
        indent + 3,
        "source: wgpu::ShaderSource::Wgsl(::std::borrow::Cow::Borrowed(WGSL_SOURCE)),",
    );
    indent_line(output, indent + 2, "})");
    indent_line(output, indent + 1, "}");
    output.push('\n');

    indent_line(
        output,
        indent + 1,
        "pub fn create_pipeline_layout(device: &wgpu::Device) -> wgpu::PipelineLayout {",
    );
    for bind_group in &entry.bind_groups {
        let origin = bind_group_origin(entry, bind_group);
        let from: Vec<String> = entry
            .rust_mod_path
            .iter()
            .cloned()
            .chain(std::iter::once(entry_module_ident(entry)))
            .collect();
        let rel = relative_module_path(&from, &origin);
        let path = if rel == "self" {
            format!("group{}", bind_group.group)
        } else {
            format!("{}::group{}", rel, bind_group.group)
        };
        indent_line(
            output,
            indent + 2,
            &format!(
                "let group{} = {}::create_bind_group_layout(device);",
                bind_group.group, path
            ),
        );
    }
    let bind_group_layouts = entry
        .bind_groups
        .iter()
        .map(|bind_group| format!("Some(&group{})", bind_group.group))
        .collect::<Vec<_>>();
    indent_line(
        output,
        indent + 2,
        &format!(
            "let bind_group_layouts = [{}];",
            bind_group_layouts.join(", ")
        ),
    );
    indent_line(
        output,
        indent + 2,
        "device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {",
    );
    indent_line(output, indent + 3, "label: Some(SHADER_NAME),");
    indent_line(
        output,
        indent + 3,
        "bind_group_layouts: &bind_group_layouts,",
    );
    indent_line(
        output,
        indent + 3,
        &format!(
            "immediate_size: {},",
            reflected_entry.push_constant_size.unwrap_or_else(|| entry
                .push_constants
                .as_ref()
                .map(|pc| pc.size)
                .unwrap_or(0))
        ),
    );
    indent_line(output, indent + 2, "})");
    indent_line(output, indent + 1, "}");
    output.push('\n');

    // Generate pipeline creation helpers based on shader stage
    match entry.stage {
        ShaderStage::Compute => {
            // Compute pipeline helper
            if let Some(_wg) = entry.workgroup_size {
                indent_line(
                    output,
                    indent + 1,
                    "pub fn create_compute_pipeline(device: &wgpu::Device) -> wgpu::ComputePipeline {",
                );
                indent_line(
                    output,
                    indent + 2,
                    "let module = create_shader_module(device);",
                );
                indent_line(
                    output,
                    indent + 2,
                    "let layout = create_pipeline_layout(device);",
                );
                indent_line(
                    output,
                    indent + 2,
                    "device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {",
                );
                indent_line(output, indent + 3, "label: Some(SHADER_NAME),");
                indent_line(output, indent + 3, "layout: Some(&layout),");
                indent_line(output, indent + 3, "module: &module,");
                indent_line(output, indent + 3, "entry_point: Some(ENTRY_POINT),");
                indent_line(
                    output,
                    indent + 3,
                    "compilation_options: wgpu::PipelineCompilationOptions { constants: &[], ..Default::default() },",
                );
                indent_line(output, indent + 3, "cache: None,");
                indent_line(output, indent + 2, "})");
                indent_line(output, indent + 1, "}");
                output.push('\n');
            }
        }
        ShaderStage::Vertex | ShaderStage::Fragment => {
            // For vertex/fragment shaders, we don't generate a full render pipeline
            // because it needs application-level configuration (color targets, depth, etc.).
            // We generate convenience functions for module + layout only.
        }
    }

    indent_line(
        output,
        indent + 1,
        "pub fn reflection() -> &'static EntryReflection { &ENTRY_REFLECTION }",
    );
    indent_line(output, indent, "}");
    output.push('\n');
    Ok(())
}

fn render_bind_group_module(
    output: &mut String,
    bind_group: &BindGroupInfo,
    binding_sizes: &BTreeMap<String, Option<u64>>,
    _origin_name: &str,
    indent: usize,
) -> Result<(), BindgenError> {
    indent_line(
        output,
        indent,
        &format!("pub mod group{} {{", bind_group.group),
    );

    // MIN_SIZE constants only for buffer bindings (not textures/samplers).
    //
    // Missing sizes are silently skipped. This happens legitimately for:
    //   1. Runtime-sized arrays — always None (no static size).
    //   2. Render-block entries — the binding may be used by the partner
    //      shader but not this one, so it is absent from the split WGSL.
    //   3. Deduplicated module-level bind groups — the merged binding sizes
    //      may not cover every binding if some entries DCE'd it away.
    for binding in &bind_group.bindings {
        if is_buffer_binding(&binding.ty) && !is_runtime_array(&binding.ty) {
            let sanitized = sanitize_wgsl_identifier(&binding.name);
            if let Some(min_binding_size) = binding_sizes.get(&sanitized).copied().flatten() {
                indent_line(
                    output,
                    indent + 1,
                    &format!(
                        "pub const BINDING_{}_MIN_SIZE: Option<u64> = {};",
                        binding.binding,
                        option_u64_literal(Some(min_binding_size))
                    ),
                );
            }
        }
    }

    indent_line(
        output,
        indent + 1,
        &format!(
            "pub const LAYOUT_ENTRIES: [wgpu::BindGroupLayoutEntry; {}] = [",
            bind_group.bindings.len()
        ),
    );
    let group_has_non_filterable_texture = has_non_filterable_texture(&bind_group.bindings);
    for binding in &bind_group.bindings {
        let min_binding_size = if is_buffer_binding(&binding.ty) && !is_runtime_array(&binding.ty) {
            let sanitized = sanitize_wgsl_identifier(&binding.name);
            binding_sizes.get(&sanitized).copied().flatten()
        } else {
            None
        };
        let count = binding_array_count(&binding.ty);
        emit_plain_comment(
            output,
            indent + 2,
            &format!("@binding({}): \"{}\"", binding.binding, binding.name),
        );
        indent_line(output, indent + 2, "wgpu::BindGroupLayoutEntry {");
        indent_line(
            output,
            indent + 3,
            &format!("binding: {},", binding.binding),
        );
        indent_line(
            output,
            indent + 3,
            &format!("visibility: {},", all_shader_stages()),
        );
        indent_line(
            output,
            indent + 3,
            &format!(
                "ty: {},",
                wgpu_binding_type(
                    &binding.ty,
                    binding.address_space,
                    min_binding_size,
                    &binding.hints,
                    group_has_non_filterable_texture,
                )
            ),
        );
        indent_line(
            output,
            indent + 3,
            &format!("count: {},", count_literal(count)),
        );
        indent_line(output, indent + 2, "},");
    }
    indent_line(output, indent + 1, "];");
    output.push('\n');

    // Emit sampler descriptor helpers for sampler bindings with @samplerState hints.
    for binding in &bind_group.bindings {
        if is_sampler_binding(&binding.ty) && !binding.hints.is_empty() {
            if let Some(desc) = sampler_descriptor_helper(binding, indent + 1) {
                output.push_str(&desc);
                output.push('\n');
            }
        }
    }

    indent_line(output, indent + 1, "#[derive(Clone)]");
    indent_line(output, indent + 1, "pub struct Entries<'a> {");
    for binding in &bind_group.bindings {
        emit_doc_comment(output, indent + 2, binding.doc.as_deref());
        indent_line(
            output,
            indent + 2,
            &format!(
                "pub {}: {},",
                rust_field_ident(&binding.name),
                rust_entry_type(&binding.ty)
            ),
        );
    }
    indent_line(output, indent + 1, "}");
    output.push('\n');

    indent_line(output, indent + 1, "impl<'a> Entries<'a> {");
    indent_line(
        output,
        indent + 2,
        &format!(
            "pub fn to_wgpu_entries(&self) -> [wgpu::BindGroupEntry<'a>; {}] {{",
            bind_group.bindings.len()
        ),
    );
    indent_line(output, indent + 3, "[");
    for binding in &bind_group.bindings {
        indent_line(output, indent + 4, "wgpu::BindGroupEntry {");
        indent_line(
            output,
            indent + 5,
            &format!("binding: {},", binding.binding),
        );
        indent_line(
            output,
            indent + 5,
            &format!(
                "resource: self.{}.clone(),",
                rust_field_ident(&binding.name)
            ),
        );
        indent_line(output, indent + 4, "},");
    }
    indent_line(output, indent + 3, "]");
    indent_line(output, indent + 2, "}");
    output.push('\n');

    indent_line(output, indent + 2, "pub fn create_bind_group(");
    indent_line(output, indent + 3, "&self,");
    indent_line(output, indent + 3, "device: &wgpu::Device,");
    indent_line(output, indent + 3, "layout: &wgpu::BindGroupLayout,");
    indent_line(output, indent + 3, "label: Option<&str>,");
    indent_line(output, indent + 2, ") -> wgpu::BindGroup {");
    indent_line(output, indent + 3, "let entries = self.to_wgpu_entries();");
    indent_line(
        output,
        indent + 3,
        "device.create_bind_group(&wgpu::BindGroupDescriptor {",
    );
    indent_line(output, indent + 4, "label,");
    indent_line(output, indent + 4, "layout,");
    indent_line(output, indent + 4, "entries: &entries,");
    indent_line(output, indent + 3, "})");
    indent_line(output, indent + 2, "}");
    indent_line(output, indent + 1, "}");
    output.push('\n');

    indent_line(
        output,
        indent + 1,
        "pub fn create_bind_group_layout(device: &wgpu::Device) -> wgpu::BindGroupLayout {",
    );
    indent_line(
        output,
        indent + 2,
        "device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {",
    );
    indent_line(output, indent + 3, "label: None,");
    indent_line(output, indent + 3, "entries: &LAYOUT_ENTRIES,");
    indent_line(output, indent + 2, "})");
    indent_line(output, indent + 1, "}");

    indent_line(output, indent, "}");
    output.push('\n');
    Ok(())
}

