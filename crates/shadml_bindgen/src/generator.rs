fn interface_hash(entry: &CompiledEntry, reflected_entry: &ReflectedEntry) -> String {
    let mut state = 0xcbf29ce484222325u64;
    hash_bytes(&mut state, entry.shader_name.as_bytes());
    hash_bytes(&mut state, entry.entry_point.as_bytes());
    hash_bytes(&mut state, entry.wgsl_source.as_bytes());
    hash_bytes(&mut state, shader_stage_variant(entry.stage).as_bytes());
    for bind_group in &entry.bind_groups {
        hash_bytes(&mut state, &bind_group.group.to_le_bytes());
        for binding in &bind_group.bindings {
            hash_bytes(&mut state, binding.name.as_bytes());
            hash_bytes(&mut state, &binding.binding.to_le_bytes());
            hash_bytes(&mut state, manifest_type_name(&binding.ty).as_bytes());
            if let Some(size) = reflected_entry
                .binding_sizes
                .get(&sanitize_wgsl_identifier(&binding.name))
                .copied()
                .flatten()
            {
                hash_bytes(&mut state, &size.to_le_bytes());
            }
        }
    }
    format!("{:016x}", state)
}

fn abi_hash(
    entry: &CompiledEntry,
    reflected_entry: &ReflectedEntry,
    reflection: &ReflectedProfile,
) -> String {
    let mut state = 0xcbf29ce484222325u64;
    hash_bytes(&mut state, shader_stage_variant(entry.stage).as_bytes());
    for bind_group in &entry.bind_groups {
        hash_bytes(&mut state, &bind_group.group.to_le_bytes());
        for binding in &bind_group.bindings {
            hash_bytes(&mut state, binding.name.as_bytes());
            hash_bytes(&mut state, &binding.binding.to_le_bytes());
            hash_bytes(
                &mut state,
                binding_address_space_variant(binding.address_space).as_bytes(),
            );
            hash_bytes(&mut state, manifest_type_name(&binding.ty).as_bytes());
            if let Some(size) = reflected_entry
                .binding_sizes
                .get(&sanitize_wgsl_identifier(&binding.name))
                .copied()
                .flatten()
            {
                hash_bytes(&mut state, &size.to_le_bytes());
            }
        }
    }
    for type_name in &entry.exported_type_names {
        let key = namespaced_struct_key(&entry.rust_mod_path, &sanitize_wgsl_identifier(type_name));
        if let Some(layout) = reflection.structs.get(&key) {
            hash_bytes(&mut state, type_name.as_bytes());
            hash_bytes(&mut state, &layout.size.to_le_bytes());
            hash_bytes(&mut state, &layout.alignment.to_le_bytes());
            for field in &layout.fields {
                hash_bytes(&mut state, field.name.as_bytes());
                hash_bytes(&mut state, &field.offset.to_le_bytes());
            }
        }
    }
    if let Some(pc) = &entry.push_constants {
        hash_bytes(&mut state, pc.name.as_bytes());
        hash_bytes(&mut state, &pc.size.to_le_bytes());
    }
    if let Some(pc_size) = reflected_entry.push_constant_size {
        hash_bytes(&mut state, &pc_size.to_le_bytes());
    }
    format!("{:016x}", state)
}

fn hash_bytes(state: &mut u64, bytes: &[u8]) {
    for byte in bytes {
        *state ^= u64::from(*byte);
        *state = state.wrapping_mul(0x100000001b3);
    }
}

fn embedded_source(source: &str, source_mode: SourceMode) -> String {
    match source_mode {
        SourceMode::EmbeddedDebug => source.to_string(),
        SourceMode::EmbeddedMinified => minify_wgsl(source),
        SourceMode::RuntimeBlob | SourceMode::ServerFetch => source.to_string(),
    }
}

fn minify_wgsl(source: &str) -> String {
    let mut result = String::with_capacity(source.len());
    let chars: Vec<char> = source.chars().collect();
    let mut i = 0;
    let mut in_string = false;
    let mut prev_was_backslash = false;

    while i < chars.len() {
        let c = chars[i];

        if in_string {
            result.push(c);
            if prev_was_backslash {
                prev_was_backslash = false;
            } else if c == '"' {
                in_string = false;
            } else if c == '\\' {
                prev_was_backslash = true;
            }
            i += 1;
            continue;
        }

        // Not in a string literal
        if c == '"' {
            result.push(c);
            in_string = true;
            i += 1;
            continue;
        }

        // Check for line comment
        if c == '/' && i + 1 < chars.len() && chars[i + 1] == '/' {
            // Skip to end of line
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
            continue;
        }

        // Check for block comment
        if c == '/' && i + 1 < chars.len() && chars[i + 1] == '*' {
            i += 2; // skip /*
            while i + 1 < chars.len() {
                if chars[i] == '*' && chars[i + 1] == '/' {
                    i += 2;
                    break;
                }
                i += 1;
            }
            continue;
        }

        // Normal character: skip whitespace, but emit a single space
        // if we're between two non-whitespace tokens.
        if c.is_whitespace() {
            if !result.is_empty() && !result.ends_with(' ') {
                result.push(' ');
            }
        } else {
            result.push(c);
        }
        i += 1;
    }

    result.trim().to_string()
}

fn rust_wire_type(ty: &ManifestType) -> Result<String, BindgenError> {
    match ty {
        ManifestType::I32 => Ok("i32".into()),
        ManifestType::U32 => Ok("u32".into()),
        ManifestType::F32 => Ok("f32".into()),
        ManifestType::Bool => Err(BindgenError::UnsupportedType(
            "bool is not supported for bytemuck wire types".into(),
        )),
        ManifestType::Vec(size, inner) => Ok(format!("[{}; {}]", rust_scalar_type(inner)?, size)),
        ManifestType::Mat(columns, rows, inner) => Ok(format!(
            "[{}; {}]",
            rust_wire_type(&ManifestType::Vec(*rows, inner.clone()))?,
            columns
        )),
        ManifestType::Struct(name) => Ok(format!("{}Wire", rust_type_ident(name))),
        ManifestType::Array(inner, len) => Ok(format!("[{}; {}]", rust_wire_type(inner)?, len)),
        ManifestType::RuntimeArray(_) => Err(BindgenError::UnsupportedType(
            "runtime-sized arrays are not supported in generated bytemuck wire structs".into(),
        )),
        ManifestType::Texture2d(_)
        | ManifestType::Texture2dMultisampled(_)
        | ManifestType::Texture2dArray(_)
        | ManifestType::Sampler
        | ManifestType::SamplerComparison => Err(BindgenError::UnsupportedType(
            "opaque resource types are not supported in generated wire structs".into(),
        )),
        ManifestType::BindingArray(_, _) => Err(BindgenError::UnsupportedType(
            "binding arrays are not supported in generated wire structs".into(),
        )),
        ManifestType::Unit => Err(BindgenError::UnsupportedType(
            "unit types are not supported in generated wire structs".into(),
        )),
    }
}

/// Rust type for the clean (idiomatic) surface struct.
/// Generate the expression that converts a clean field value to its wire representation.
fn clean_to_wire_expr(field_name: &str, ty: &ManifestType, preset: TypeMapPreset) -> String {
    let wire_ty = rust_wire_type(ty).unwrap_or_default();
    let clean_ty = clean_rust_type(ty, preset).unwrap_or_default();
    if wire_ty == clean_ty {
        format!("value.{}", field_name)
    } else if clean_ty == "glam::Mat4" || clean_ty == "glam::Mat3" || clean_ty == "glam::Mat2" {
        format!("value.{}.to_cols_array_2d()", field_name)
    } else {
        format!("value.{}.into()", field_name)
    }
}

fn clean_rust_type(ty: &ManifestType, preset: TypeMapPreset) -> Result<String, BindgenError> {
    match ty {
        ManifestType::I32 => Ok("i32".into()),
        ManifestType::U32 => Ok("u32".into()),
        ManifestType::F32 => Ok("f32".into()),
        ManifestType::Bool => Err(BindgenError::UnsupportedType(
            "bool is not supported in generated clean types".into(),
        )),
        ManifestType::Vec(size, inner) => match preset {
            TypeMapPreset::Plain => Ok(format!("[{}; {}]", rust_scalar_type(inner)?, size)),
            TypeMapPreset::Glam | TypeMapPreset::Nalgebra => glam_vec_type(*size, inner),
        },
        ManifestType::Mat(columns, rows, inner) => match preset {
            TypeMapPreset::Plain => Ok(format!(
                "[{}; {}]",
                clean_rust_type(&ManifestType::Vec(*rows, inner.clone()), preset)?,
                columns
            )),
            TypeMapPreset::Glam | TypeMapPreset::Nalgebra => glam_mat_type(*columns, *rows, inner),
        },
        ManifestType::Struct(name) => Ok(rust_type_ident(name)),
        ManifestType::Array(inner, len) => {
            Ok(format!("[{}; {}]", clean_rust_type(inner, preset)?, len))
        }
        ManifestType::RuntimeArray(_) => Err(BindgenError::UnsupportedType(
            "runtime-sized arrays are not supported in generated clean types".into(),
        )),
        ManifestType::Texture2d(_)
        | ManifestType::Texture2dMultisampled(_)
        | ManifestType::Texture2dArray(_)
        | ManifestType::Sampler
        | ManifestType::SamplerComparison => Err(BindgenError::UnsupportedType(
            "opaque resource types are not supported in generated clean types".into(),
        )),
        ManifestType::BindingArray(_, _) => Err(BindgenError::UnsupportedType(
            "binding arrays are not supported in generated clean types".into(),
        )),
        ManifestType::Unit => Err(BindgenError::UnsupportedType(
            "unit types are not supported in generated clean types".into(),
        )),
    }
}

