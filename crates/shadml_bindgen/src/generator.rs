fn rust_wire_size(
    ty: &ManifestType,
    module_path: &[String],
    reflection: &ReflectedProfile,
) -> Result<u32, BindgenError> {
    match ty {
        ManifestType::I32 | ManifestType::U32 | ManifestType::F32 => Ok(4),
        ManifestType::Bool => Err(BindgenError::UnsupportedType(
            "bool is not supported for bytemuck wire types".into(),
        )),
        ManifestType::Vec(size, inner) => {
            Ok(rust_wire_size(inner, module_path, reflection)? * u32::from(*size))
        }
        ManifestType::Mat(columns, rows, inner) => Ok(rust_wire_size(
            &ManifestType::Vec(*rows, inner.clone()),
            module_path,
            reflection,
        )? * u32::from(*columns)),
        ManifestType::Struct(name) => {
            let key = namespaced_struct_key(module_path, &sanitize_wgsl_identifier(name));
            reflection
                .structs
                .get(&key)
                .map(|layout| layout.size)
                .ok_or_else(|| {
                    BindgenError::InvalidManifest(format!(
                        "missing reflected layout for nested type '{}'",
                        name
                    ))
                })
        }
        ManifestType::Array(inner, len) => {
            Ok(rust_wire_size(inner, module_path, reflection)? * len)
        }
        ManifestType::RuntimeArray(_) => Err(BindgenError::UnsupportedType(
            "runtime-sized arrays are not supported in generated bytemuck wire structs".into(),
        )),
        ManifestType::Texture2d(_)
        | ManifestType::Texture2dMultisampled(_)
        | ManifestType::Texture2dArray(_)
        | ManifestType::Sampler
        | ManifestType::SamplerComparison => Err(BindgenError::UnsupportedType(
            "opaque resource types do not have a wire size".into(),
        )),
        ManifestType::BindingArray(_, _) => Err(BindgenError::UnsupportedType(
            "binding arrays are not supported in generated wire structs".into(),
        )),
        ManifestType::Unit => Err(BindgenError::UnsupportedType(
            "unit types are not supported in generated wire structs".into(),
        )),
    }
}

fn rust_scalar_type(ty: &ManifestType) -> Result<&'static str, BindgenError> {
    match ty {
        ManifestType::I32 => Ok("i32"),
        ManifestType::U32 => Ok("u32"),
        ManifestType::F32 => Ok("f32"),
        other => Err(BindgenError::InvalidManifest(format!(
            "expected scalar type, got {:?}",
            other
        ))),
    }
}

fn manifest_type_name(ty: &ManifestType) -> String {
    match ty {
        ManifestType::I32 => "i32".into(),
        ManifestType::U32 => "u32".into(),
        ManifestType::F32 => "f32".into(),
        ManifestType::Bool => "bool".into(),
        ManifestType::Vec(size, inner) => format!("vec{}<{}>", size, manifest_type_name(inner)),
        ManifestType::Mat(columns, rows, inner) => {
            format!("mat{}x{}<{}>", columns, rows, manifest_type_name(inner))
        }
        ManifestType::Struct(name) => name.clone(),
        ManifestType::Array(inner, len) => {
            format!("array<{}, {}>", manifest_type_name(inner), len)
        }
        ManifestType::RuntimeArray(inner) => format!("array<{}>", manifest_type_name(inner)),
        ManifestType::Texture2d(inner) => format!("texture_2d<{}>", manifest_type_name(inner)),
        ManifestType::Texture2dMultisampled(inner) => {
            format!("texture_multisampled_2d<{}>", manifest_type_name(inner))
        }
        ManifestType::Texture2dArray(inner) => {
            format!("texture_2d_array<{}>", manifest_type_name(inner))
        }
        ManifestType::Sampler => "sampler".into(),
        ManifestType::SamplerComparison => "sampler_comparison".into(),
        ManifestType::BindingArray(inner, count) => {
            format!("binding_array<{}, {}>", manifest_type_name(inner), count)
        }
        ManifestType::Unit => "()".into(),
    }
}

fn string_slice_literal(values: &[String]) -> String {
    let mut literal = String::from("[");
    for (index, value) in values.iter().enumerate() {
        if index > 0 {
            literal.push_str(", ");
        }
        write!(literal, "{:?}", value).unwrap();
    }
    literal.push(']');
    literal
}

