fn render_registry(
    output: &mut String,
    manifest: &ShaderBundleManifest,
    _reflections: &ReflectedManifest,
    registry_entries: &[RegistryEntry],
) -> Result<(), BindgenError> {
    writeln!(output, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(output, "pub enum ShaderEntry {{").unwrap();
    for entry in registry_entries {
        writeln!(output, "    {},", entry.variant).unwrap();
    }
    writeln!(output, "}}\n").unwrap();

    writeln!(output, "impl ShaderEntry {{").unwrap();
    render_registry_match_method(
        output,
        manifest,
        registry_entries,
        "wgsl_source",
        "&'static str",
        |profile, entry| {
            format!(
                "profiles::{}::{}::{}::WGSL_SOURCE",
                rust_module_ident(&profile.profile_key),
                module_access_path(&entry.rust_mod_path),
                entry_module_ident(entry)
            )
        },
    )?;
    render_registry_match_method(
        output,
        manifest,
        registry_entries,
        "entry_point",
        "&'static str",
        |profile, entry| {
            format!(
                "profiles::{}::{}::{}::ENTRY_POINT",
                rust_module_ident(&profile.profile_key),
                module_access_path(&entry.rust_mod_path),
                entry_module_ident(entry)
            )
        },
    )?;
    render_registry_match_method(
        output,
        manifest,
        registry_entries,
        "reflection",
        "&'static EntryReflection",
        |profile, entry| {
            format!(
                "profiles::{}::{}::{}::reflection()",
                rust_module_ident(&profile.profile_key),
                module_access_path(&entry.rust_mod_path),
                entry_module_ident(entry)
            )
        },
    )?;
    render_registry_match_method(
        output,
        manifest,
        registry_entries,
        "create_shader_module",
        "wgpu::ShaderModule",
        |profile, entry| {
            format!(
                "profiles::{}::{}::{}::create_shader_module(device)",
                rust_module_ident(&profile.profile_key),
                module_access_path(&entry.rust_mod_path),
                entry_module_ident(entry)
            )
        },
    )?;
    render_registry_match_method(
        output,
        manifest,
        registry_entries,
        "create_pipeline_layout",
        "wgpu::PipelineLayout",
        |profile, entry| {
            format!(
                "profiles::{}::{}::{}::create_pipeline_layout(device)",
                rust_module_ident(&profile.profile_key),
                module_access_path(&entry.rust_mod_path),
                entry_module_ident(entry)
            )
        },
    )?;

    writeln!(
        output,
        "    pub fn create_bind_group_layout(self, device: &wgpu::Device, profile: ShaderProfile, group: u32) -> wgpu::BindGroupLayout {{"
    )
    .unwrap();
    writeln!(output, "        match (self, profile, group) {{").unwrap();
    for profile in &manifest.profiles {
        for entry in &profile.entries {
            for bind_group in &entry.bind_groups {
                let origin = bind_group_origin(entry, bind_group);
                writeln!(
                    output,
                    "            (ShaderEntry::{}, ShaderProfile::{}, {}) => profiles::{}::{}::group{}::create_bind_group_layout(device),",
                    entry_variant(entry),
                    rust_variant_ident(&profile.profile_key),
                    bind_group.group,
                    rust_module_ident(&profile.profile_key),
                    module_access_path(&origin),
                    bind_group.group
                )
                .unwrap();
            }
        }
    }
    writeln!(
        output,
        "            (_, _, _) => unreachable!(\"bind group layout should always be available for a valid (entry, profile, group) combination\"),"
    )
    .unwrap();
    writeln!(output, "        }}").unwrap();
    writeln!(output, "    }}").unwrap();

    writeln!(
        output,
        "    pub fn source_files(self, profile: ShaderProfile) -> &'static [&'static str] {{ self.reflection(profile).source_files }}"
    )
    .unwrap();
    writeln!(
        output,
        "    pub fn interface_hash(self, profile: ShaderProfile) -> &'static str {{ self.reflection(profile).interface_hash }}"
    )
    .unwrap();
    writeln!(
        output,
        "    pub fn abi_hash(self, profile: ShaderProfile) -> &'static str {{ self.reflection(profile).abi_hash }}"
    )
    .unwrap();
    writeln!(
        output,
        "    pub fn compatibility_between(self, from: ShaderProfile, to: ShaderProfile) -> ProfileCompatibility {{"
    )
    .unwrap();
    writeln!(
        output,
        "        if self.abi_hash(from) == self.abi_hash(to) {{ ProfileCompatibility::AbiStable }} else {{ ProfileCompatibility::AbiChanged }}"
    )
    .unwrap();
    writeln!(output, "    }}").unwrap();
    writeln!(output, "}}\n").unwrap();

    writeln!(
        output,
        "pub const ALL_SHADER_ENTRIES: &[ShaderEntry] = &[{}];",
        registry_entries
            .iter()
            .map(|entry| format!("ShaderEntry::{}", entry.variant))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();

    Ok(())
}

fn render_registry_match_method<F>(
    output: &mut String,
    manifest: &ShaderBundleManifest,
    registry_entries: &[RegistryEntry],
    name: &str,
    return_ty: &str,
    expr: F,
) -> Result<(), BindgenError>
where
    F: Fn(&CompiledProfile, &CompiledEntry) -> String,
{
    let signature = match name {
        "create_shader_module" | "create_pipeline_layout" => {
            format!(
                "    pub fn {}(self, device: &wgpu::Device, profile: ShaderProfile) -> {} {{",
                name, return_ty
            )
        }
        _ => format!(
            "    pub fn {}(self, profile: ShaderProfile) -> {} {{",
            name, return_ty
        ),
    };
    writeln!(output, "{}", signature).unwrap();
    writeln!(output, "        match (self, profile) {{").unwrap();
    for profile in &manifest.profiles {
        for registry_entry in registry_entries {
            let compiled_entry = profile
                .entries
                .iter()
                .find(|entry| entry_key(entry) == registry_entry.key)
                .ok_or_else(|| {
                    BindgenError::InvalidManifest(format!(
                        "profile '{}' does not contain entry '{}'",
                        profile.profile_key, registry_entry.key
                    ))
                })?;
            writeln!(
                output,
                "            (ShaderEntry::{}, ShaderProfile::{}) => {},",
                registry_entry.variant,
                rust_variant_ident(&profile.profile_key),
                expr(profile, compiled_entry)
            )
            .unwrap();
        }
    }
    writeln!(output, "        }}").unwrap();
    writeln!(output, "    }}\n").unwrap();
    Ok(())
}

fn collect_registry_entries(
    manifest: &ShaderBundleManifest,
) -> Result<Vec<RegistryEntry>, BindgenError> {
    let first_profile = manifest
        .profiles
        .first()
        .ok_or_else(|| BindgenError::InvalidManifest("manifest has no profiles".into()))?;
    let mut registry_entries = first_profile
        .entries
        .iter()
        .map(|entry| RegistryEntry {
            key: entry_key(entry),
            variant: entry_variant(entry),
        })
        .collect::<Vec<_>>();
    registry_entries.sort_by(|lhs, rhs| lhs.key.cmp(&rhs.key));

    let baseline = registry_entries
        .iter()
        .map(|entry| entry.key.clone())
        .collect::<BTreeSet<_>>();
    for profile in manifest.profiles.iter().skip(1) {
        let current = profile
            .entries
            .iter()
            .map(entry_key)
            .collect::<BTreeSet<_>>();
        if current != baseline {
            return Err(BindgenError::InvalidManifest(format!(
                "profile '{}' has a different entry set than profile '{}'",
                profile.profile_key, first_profile.profile_key
            )));
        }
    }

    Ok(registry_entries)
}

fn insert_entry(root: &mut ModuleNode, entry: &CompiledEntry, index: usize) {
    let mut node = root;
    for segment in &entry.rust_mod_path {
        node = node.children.entry(segment.clone()).or_default();
    }
    node.entry_indices.push(index);
}

fn insert_exported_types(root: &mut ModuleNode, profile: &CompiledProfile) {
    // Only insert types that are actually referenced by at least one entry point.
    // This avoids inserting types that survive into the pre-DCE exported_types
    // but are eliminated from all per-entry WGSL outputs.
    let used_type_names: std::collections::HashSet<String> = profile
        .entries
        .iter()
        .flat_map(|e| e.exported_type_names.iter().cloned())
        .collect();
    for exported in &profile.exported_types {
        if !used_type_names.contains(&exported.name) {
            continue;
        }
        let mut node = &mut *root;
        for segment in &exported.rust_mod_path {
            node = node.children.entry(segment.clone()).or_default();
        }
        node.type_names.insert(exported.name.clone());
    }
}

fn insert_bind_groups(root: &mut ModuleNode, profile: &CompiledProfile) {
    // Collect all bind groups keyed by (origin_module_path, group), merging
    // bindings across entries so that the emitted bind group contains the
    // union of all bindings used by any entry that references it.
    let mut merged: BTreeMap<(Vec<String>, u32), BindGroupInfo> = BTreeMap::new();

    for entry in &profile.entries {
        for bind_group in &entry.bind_groups {
            let origin = bind_group_origin(entry, bind_group);
            let key = (origin.clone(), bind_group.group);
            let existing = merged.entry(key).or_insert_with(|| BindGroupInfo {
                group: bind_group.group,
                bindings: Vec::new(),
            });
            // Merge bindings, avoiding duplicates by binding number
            for binding in &bind_group.bindings {
                if !existing
                    .bindings
                    .iter()
                    .any(|b| b.binding == binding.binding)
                {
                    existing.bindings.push(binding.clone());
                }
            }
            existing.bindings.sort_by_key(|b| b.binding);
        }
    }

    // Insert merged bind groups into the module tree at their origin paths
    for ((origin, _group), bind_group) in merged {
        let mut node = &mut *root;
        for segment in &origin {
            node = node.children.entry(segment.clone()).or_default();
        }
        node.bind_groups.insert(bind_group.group, bind_group);
    }
}

fn entry_key(entry: &CompiledEntry) -> String {
    format!(
        "{}::{}::{}",
        entry.rust_mod_path.join("."),
        entry.entry_point,
        shader_stage_variant(entry.stage)
    )
}

fn entry_variant(entry: &CompiledEntry) -> String {
    entry
        .rust_mod_path
        .iter()
        .chain(std::iter::once(&entry.entry_point))
        .chain(std::iter::once(
            &shader_stage_variant(entry.stage).to_string(),
        ))
        .map(|segment| rust_variant_ident(segment))
        .collect::<Vec<_>>()
        .join("")
}

fn entry_module_ident(entry: &CompiledEntry) -> String {
    format!(
        "{}_{}",
        rust_module_ident(&entry.entry_point),
        rust_module_ident(shader_stage_variant(entry.stage))
    )
}

fn shader_stage_variant(stage: ShaderStage) -> &'static str {
    match stage {
        ShaderStage::Compute => "Compute",
        ShaderStage::Vertex => "Vertex",
        ShaderStage::Fragment => "Fragment",
    }
}

fn module_access_path(path: &[String]) -> String {
    path.iter()
        .map(|segment| rust_module_ident(segment))
        .collect::<Vec<_>>()
        .join("::")
}

fn namespaced_struct_key(module_path: &[String], name: &str) -> String {
    if module_path.is_empty() {
        name.to_string()
    } else {
        format!("{}.{}", module_path.join("."), name)
    }
}

/// Compute a relative Rust module path from `from` to `to`.
/// Returns a string like "super::super::global_bindings".
fn relative_module_path(from: &[String], to: &[String]) -> String {
    let from: Vec<String> = from.iter().map(|s| rust_module_ident(s)).collect();
    let to: Vec<String> = to.iter().map(|s| rust_module_ident(s)).collect();
    let common = from
        .iter()
        .zip(to.iter())
        .take_while(|(a, b)| a == b)
        .count();
    let up_count = from.len() - common;
    let down = &to[common..];
    let mut parts: Vec<String> = (0..up_count).map(|_| "super".to_string()).collect();
    parts.extend_from_slice(down);
    if parts.is_empty() {
        "self".to_string()
    } else {
        parts.join("::")
    }
}

fn all_shader_stages() -> &'static str {
    "wgpu::ShaderStages::all()"
}

/// Determine the origin module path for a bind group within an entry.
/// Returns the origin module if all bindings in the group share the same
/// origin and it differs from the entry's module. Otherwise returns the
/// entry's module path (meaning the bind group is local or mixed-origin).
fn bind_group_origin(entry: &CompiledEntry, bind_group: &BindGroupInfo) -> Vec<String> {
    let first_origin = bind_group.bindings.first().map(|b| b.origin_module.clone());
    let all_same_origin = first_origin.as_ref().is_none_or(|origin| {
        bind_group
            .bindings
            .iter()
            .all(|b| &b.origin_module == origin)
    });
    if all_same_origin {
        if let Some(origin) = first_origin {
            // Empty origin means the binding wasn't tracked to a specific module
            // (e.g. render-block bindings), so treat it as local.
            if origin.is_empty() || origin == entry.rust_mod_path {
                entry.rust_mod_path.clone()
            } else {
                origin
            }
        } else {
            entry.rust_mod_path.clone()
        }
    } else {
        entry.rust_mod_path.clone()
    }
}

fn find_reflected_layout<'a>(
    reflection: &'a ReflectedProfile,
    module_path: &[String],
    name: &str,
    candidate_paths: &[Vec<String>],
) -> Option<&'a StructLayout> {
    // 1. Try the exact origin path.
    let key = namespaced_struct_key(module_path, name);
    if let Some(layout) = reflection.structs.get(&key) {
        return Some(layout);
    }

    // 2. Try entry paths of entries in the same module.
    for path in candidate_paths {
        let key = namespaced_struct_key(path, name);
        if let Some(layout) = reflection.structs.get(&key) {
            return Some(layout);
        }
    }

    None
}

fn buffer_binding_type(address_space: BindingAddressSpace) -> &'static str {
    match address_space {
        BindingAddressSpace::Uniform => "wgpu::BufferBindingType::Uniform",
        BindingAddressSpace::StorageRead => "wgpu::BufferBindingType::Storage { read_only: true }",
        BindingAddressSpace::StorageReadWrite => {
            "wgpu::BufferBindingType::Storage { read_only: false }"
        }
        BindingAddressSpace::Immediate => {
            // Immediate is a buffer binding in wgpu, treated like Uniform.
            "wgpu::BufferBindingType::Uniform"
        }
        BindingAddressSpace::Opaque => {
            unreachable!(
                "buffer_binding_type is only called for buffer address spaces (Uniform, StorageRead, StorageReadWrite, Immediate); \
                 Opaque bindings (textures/samplers) should be filtered by is_buffer_binding before reaching this function"
            )
        }
    }
}

/// Returns true if the ManifestType is a buffer (uniform/storage), not a texture/sampler.
fn is_buffer_binding(ty: &ManifestType) -> bool {
    matches!(
        ty,
        ManifestType::I32
            | ManifestType::U32
            | ManifestType::F32
            | ManifestType::Bool
            | ManifestType::Vec(..)
            | ManifestType::Mat(..)
            | ManifestType::Struct(_)
            | ManifestType::Array(..)
            | ManifestType::RuntimeArray(_)
            | ManifestType::Unit
    )
}

/// Runtime-sized arrays have no CPU-side size and therefore no reflected
/// binding size; `min_binding_size` is legitimately `None` for them.
fn is_runtime_array(ty: &ManifestType) -> bool {
    matches!(ty, ManifestType::RuntimeArray(_))
}

/// Returns true if any texture binding in the bind group requires non-filterable
/// sampling (either multisampled or explicitly non-filterable via hint).
fn has_non_filterable_texture(bindings: &[BindingInfo]) -> bool {
    bindings
        .iter()
        .any(|b| is_non_filterable_texture_binding(b))
}

/// Returns true if a single binding is a float texture that requires
/// non-filterable sampling (multisampled or has `textureSampleType(filterable = false)`).
fn is_non_filterable_texture_binding(binding: &BindingInfo) -> bool {
    let (inner, multisampled) = match &binding.ty {
        ManifestType::Texture2d(inner) => (inner, false),
        ManifestType::Texture2dMultisampled(inner) => (inner, true),
        ManifestType::Texture2dArray(inner) => (inner, false),
        ManifestType::BindingArray(inner, _) => match inner.as_ref() {
            ManifestType::Texture2d(inner) => (inner, false),
            ManifestType::Texture2dMultisampled(inner) => (inner, true),
            ManifestType::Texture2dArray(inner) => (inner, false),
            _ => return false,
        },
        _ => return false,
    };
    // Only float textures can be non-filterable.
    match inner.as_ref() {
        ManifestType::F32 => {
            if multisampled {
                true // Multisampled textures are always non-filterable
            } else {
                // Check for explicit @textureSampleType(filterable = false) hint
                binding.hints.iter().any(|h| {
                    h.name == "textureSampleType"
                        && h.args.iter().any(|arg| {
                            matches!(
                                arg,
                                HintArg::Named(name, HintValue::Ident(value))
                                | HintArg::Named(name, HintValue::String(value))
                                if name == "filterable" && value == "false"
                            )
                        })
                })
            }
        }
        _ => false,
    }
}

/// Generate `wgpu::BindingType` code for a given ManifestType and address space.
fn wgpu_binding_type(
    ty: &ManifestType,
    address_space: BindingAddressSpace,
    min_binding_size: Option<u64>,
    hints: &[HintAttribute],
    group_has_non_filterable_texture: bool,
) -> String {
    match ty {
        ManifestType::Texture2d(inner) => {
            let sample_type = texture_sample_type(inner, true, hints);
            format!("wgpu::BindingType::Texture {{ view_dimension: wgpu::TextureViewDimension::D2, sample_type: {}, multisampled: false }}", sample_type)
        }
        ManifestType::Texture2dMultisampled(inner) => {
            let sample_type = texture_sample_type(inner, false, hints);
            format!("wgpu::BindingType::Texture {{ view_dimension: wgpu::TextureViewDimension::D2, sample_type: {}, multisampled: true }}", sample_type)
        }
        ManifestType::Texture2dArray(inner) => {
            let sample_type = texture_sample_type(inner, true, hints);
            format!("wgpu::BindingType::Texture {{ view_dimension: wgpu::TextureViewDimension::D2Array, sample_type: {}, multisampled: false }}", sample_type)
        }
        ManifestType::Sampler => {
            let binding_type = sampler_binding_type_from_hints(hints, group_has_non_filterable_texture);
            format!("wgpu::BindingType::Sampler(wgpu::SamplerBindingType::{})", binding_type)
        }
        ManifestType::SamplerComparison => "wgpu::BindingType::Sampler(wgpu::SamplerBindingType::Comparison)".to_string(),
        ManifestType::BindingArray(inner, _) => {
            // Recursively generate the inner type, with count handled separately
            wgpu_binding_type(inner, address_space, min_binding_size, hints, group_has_non_filterable_texture)
        }
        _ => format!(
            "wgpu::BindingType::Buffer {{ ty: {}, has_dynamic_offset: false, min_binding_size: {} }}",
            buffer_binding_type(address_space),
            option_non_zero_u64_literal(min_binding_size)
        ),
    }
}

/// Derive the wgpu SamplerBindingType from `@samplerState` hints and
/// the bind group's non-filterable texture status.
/// `filter = "nearest"` → NonFiltering.
/// If any texture in the same bind group is non-filterable, the sampler
/// must also be NonFiltering to pass pipeline validation.
fn sampler_binding_type_from_hints(
    hints: &[HintAttribute],
    group_has_non_filterable_texture: bool,
) -> &'static str {
    if group_has_non_filterable_texture {
        return "NonFiltering";
    }
    for hint in hints {
        if hint.name == "samplerState" {
            for arg in &hint.args {
                if let HintArg::Named(name, HintValue::String(value))
                | HintArg::Named(name, HintValue::Ident(value)) = arg
                {
                    if name == "filter" && value == "nearest" {
                        return "NonFiltering";
                    }
                }
            }
        }
    }
    "Filtering"
}

/// Returns true if the ManifestType is a sampler (including binding arrays of samplers).
fn is_sampler_binding(ty: &ManifestType) -> bool {
    match ty {
        ManifestType::Sampler | ManifestType::SamplerComparison => true,
        ManifestType::BindingArray(inner, _) => is_sampler_binding(inner),
        _ => false,
    }
}

/// Derive the wgpu TextureSampleType string from the inner manifest type.
/// `filterable_default` is true for non-multisampled textures (Float is filterable by default).
/// `hints` may override the filterable setting for Float inner types via `@textureSampleType`.
fn texture_sample_type(
    inner: &ManifestType,
    filterable_default: bool,
    hints: &[HintAttribute],
) -> String {
    match inner {
        ManifestType::I32 => "wgpu::TextureSampleType::Sint".to_string(),
        ManifestType::U32 => "wgpu::TextureSampleType::Uint".to_string(),
        ManifestType::F32 => {
            let filterable = if filterable_default {
                !hints.iter().any(|h| {
                    h.name == "textureSampleType"
                        && h.args.iter().any(|arg| {
                            matches!(
                                arg,
                                HintArg::Named(name, HintValue::Ident(value))
                                | HintArg::Named(name, HintValue::String(value))
                                if name == "filterable" && value == "false"
                            )
                        })
                })
            } else {
                false
            };
            format!(
                "wgpu::TextureSampleType::Float {{ filterable: {} }}",
                filterable
            )
        }
        _ => "wgpu::TextureSampleType::Float { filterable: true }".to_string(),
    }
}

/// Generate a `create_{name}_sampler` helper function if the binding has `@samplerState` hints.
fn sampler_descriptor_helper(binding: &BindingInfo, indent: usize) -> Option<String> {
    let sampler_state = binding.hints.iter().find(|h| h.name == "samplerState")?;

    let mut filter = "Linear";
    let mut mipmap_filter = "Linear";
    let mut address_mode_u = "Repeat";
    let mut address_mode_v = "Repeat";
    let mut address_mode_w = "Repeat";

    for arg in &sampler_state.args {
        if let HintArg::Named(name, HintValue::String(value))
        | HintArg::Named(name, HintValue::Ident(value)) = arg
        {
            match name.as_str() {
                "filter" => filter = wgpu_filter_mode(&value),
                "mipmap_filter" => mipmap_filter = wgpu_filter_mode(&value),
                "address_mode_u" => address_mode_u = wgpu_address_mode(&value),
                "address_mode_v" => address_mode_v = wgpu_address_mode(&value),
                "address_mode_w" => address_mode_w = wgpu_address_mode(&value),
                _ => {}
            }
        }
    }

    let name = &binding.name;
    let fn_name = sanitize_wgsl_identifier(name).to_snake_case();
    let mut out = String::new();
    indent_line(
        &mut out,
        indent,
        &format!(
            "pub fn create_{}_sampler(device: &wgpu::Device) -> wgpu::Sampler {{",
            fn_name
        ),
    );
    indent_line(
        &mut out,
        indent + 1,
        "device.create_sampler(&wgpu::SamplerDescriptor {",
    );
    indent_line(&mut out, indent + 2, &format!("label: Some(\"{}\"),", name));
    indent_line(
        &mut out,
        indent + 2,
        &format!("mag_filter: wgpu::FilterMode::{},", filter),
    );
    indent_line(
        &mut out,
        indent + 2,
        &format!("min_filter: wgpu::FilterMode::{},", filter),
    );
    indent_line(
        &mut out,
        indent + 2,
        &format!("mipmap_filter: wgpu::MipmapFilterMode::{},", mipmap_filter),
    );
    indent_line(
        &mut out,
        indent + 2,
        &format!("address_mode_u: wgpu::AddressMode::{},", address_mode_u),
    );
    indent_line(
        &mut out,
        indent + 2,
        &format!("address_mode_v: wgpu::AddressMode::{},", address_mode_v),
    );
    indent_line(
        &mut out,
        indent + 2,
        &format!("address_mode_w: wgpu::AddressMode::{},", address_mode_w),
    );
    indent_line(&mut out, indent + 2, "..Default::default()");
    indent_line(&mut out, indent + 1, "})");
    indent_line(&mut out, indent, "}");
    Some(out)
}

fn wgpu_filter_mode(value: &str) -> &'static str {
    match value {
        "nearest" => "Nearest",
        _ => "Linear",
    }
}

fn wgpu_address_mode(value: &str) -> &'static str {
    match value {
        "clamp_to_edge" => "ClampToEdge",
        "mirror_repeat" => "MirrorRepeat",
        _ => "Repeat",
    }
}

